    private void jComboBox1TipoDeDeliveryActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jComboBox1TipoDeDeliveryActionPerformed

        //JOptionPane.showMessageDialog(null, "Se ejecuto el evento");
        String tipoDelivery = jComboBox1TipoDeDelivery.getSelectedItem().toString();

        if (tipoDelivery.equals("Empaque")) {
            jTextField3Itemss.setEnabled(true);    // Es visible cuando el usuario selecciona préstamo
            jTextField4CantidadPerItem.setEnabled(true);
            jTextField2DistanceKm.setEnabled(false);

        } else if (tipoDelivery.equals("Envío en bicicleta")) {
            jTextField3Itemss.setEnabled(false);   //No es visible cuando el usuario selecciona otra opción del comboBox
            jTextField4CantidadPerItem.setEnabled(false);
            jTextField2DistanceKm.setEnabled(true);

        } else if (tipoDelivery.equals("Envío en forgoneta")) {
            jTextField3Itemss.setEnabled(false);
            jTextField2DistanceKm.setEnabled(true);
            jTextField4CantidadPerItem.setEnabled(false);
        }


    }//GEN-LAST:event_jComboBox1TipoDeDeliveryActionPerformed

    private void jButton1RegistraCobroActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton1RegistraCobroActionPerformed

        String tipoDelivery = jComboBox1TipoDeDelivery.getSelectedItem().toString();
        
        if (tipoDelivery.equals("Envío en bicicleta")){
        int distanceKm = Integer.parseInt(jTextField2DistanceKm.getText());
        String trankingId = "BIC-238";
        
        controller.registrarBikeDelivery(trankingId, distanceKm);
        double monto = controller.getChargeables().get(controller.getChargeables().size() - 1)
        .calculateCharge();
        
        JOptionPane.showMessageDialog(null, "Envío en biciclera registrado"
        +"\n código de seguimiento: "+ trankingId + "\nMonto: " + monto);
        
//        JOptionPane.showMessageDialog(null, "Monto total: ");
        
        }else if (tipoDelivery.equals("Envío en forgoneta")){
            int distanceKm = Integer.parseInt(jTextField2DistanceKm.getText());
            String trankingId = "Ford-398";
            
            controller.registrarVanDelivery(trankingId, distanceKm);
            double monto = controller.getChargeables().get(controller.getChargeables().size() - 1)
        .calculateCharge();
            
            JOptionPane.showMessageDialog(null, "Envío en forgoneta registrado"
            +"\n código de seguimiento: "+ trankingId + "\nMonto: " + monto);
        
        }else if (tipoDelivery.equals("Empaque")){
            int items = Integer.parseInt(jTextField3Itemss.getText());
            int ChargerPerItem = Integer.parseInt(jTextField4CantidadPerItem.getText());
            
            controller.registrarPackaging(items, ChargerPerItem);
            double monto = controller.getChargeables().get(controller.getChargeables().size() - 1)
        .calculateCharge();
            
            JOptionPane.showMessageDialog(null, "Empaque registrado" + "\nMonto: " + monto);
            
        }
        
        
        
    }//GEN-LAST:event_jButton1RegistraCobroActionPerformed

